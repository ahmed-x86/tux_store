//! # tux-abi — the shared kernel of Tux Store
//!
//! Every Tux Store component (search, thumbnails, install, UI) is a separate
//! shared library (`libtux_*.so`) loaded at runtime by the tiny `tux-store`
//! executable. They never call each other directly; they talk over one
//! **message bus**:
//!
//! * [`Message`] is the single typed vocabulary every module understands.
//! * [`Bus::publish`] delivers a message to *all* modules.
//! * [`Module::on_message`] receives them; irrelevant messages are ignored.
//!
//! Across the `.so` boundary only a tiny stable **C ABI** is used (see
//! [`HostApi`] and the symbols generated by [`export_module!`]); the payload is
//! UTF-8 JSON, so modules need not be built by the same compiler version.

